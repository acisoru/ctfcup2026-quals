#!/usr/bin/env python3
# Generates dfa.v: a DFA over bytes that accepts exactly the flag.
# Chain states consume the flag; some chain states get decoy edges into
# short dead-end branches so the graph is not a plain line.
import random
import sys

FLAG = b"ctfcup{9f558d7345a6b6df34f6f142732bcc7a}"
SEED = 0x7a5e
ALPHABET = b"0123456789abcdefctfup{}_"

rng = random.Random(SEED)

ids = rng.sample(range(1, 256), 160)
pool = iter(ids)

chain = [next(pool) for _ in range(len(FLAG) + 1)]  # chain[i] = after i chars
start, accept = chain[0], chain[-1]
dead = next(pool)

trans = {s: {} for s in chain}
trans[dead] = {}
for i, c in enumerate(FLAG):
    trans[chain[i]][c] = chain[i + 1]

# Decoy branches: from a chain state, a wrong char leads into a short
# path of fake states that eventually always falls into `dead`.
fakes = []
for i in range(len(FLAG)):
    for _ in range(rng.choice([0, 1, 1, 2])):
        c = rng.choice([x for x in ALPHABET if x not in trans[chain[i]]])
        prev, pc = chain[i], c
        for _ in range(rng.randint(1, 4)):
            f = next(pool)
            fakes.append(f)
            trans[f] = {}
            trans[prev][pc] = f
            prev = f
            pc = rng.choice(ALPHABET)
        # last fake state has no outgoing edges -> dead on anything

states = list(trans)
rng.shuffle(states)


def h(x):
    return "8'h%02x" % x


out = []
out.append("// generated by gen.py, do not edit")
out.append("module dfa_next(input [7:0] state, input [7:0] ch, output reg [7:0] next);")
out.append("  always @(*) begin")
out.append("    next = %s;" % h(dead))
out.append("    case (state)")
for s in states:
    edges = list(trans[s].items())
    if not edges:
        continue
    rng.shuffle(edges)
    out.append("      %s: case (ch)" % h(s))
    for c, d in edges:
        out.append("        %s: next = %s;" % (h(c), h(d)))
    out.append("        default: next = %s;" % h(dead))
    out.append("      endcase")
out.append("      default: next = %s;" % h(dead))
out.append("    endcase")
out.append("  end")
out.append("endmodule")
out.append("")
out.append("`define DFA_START %s" % h(start))
out.append("`define DFA_ACCEPT %s" % h(accept))
out.append("")

with open(sys.argv[1] if len(sys.argv) > 1 else "dfa.v", "w") as f:
    f.write("\n".join(out))

print("states: %d chain, %d fake, 1 dead" % (len(chain), len(fakes)), file=sys.stderr)
