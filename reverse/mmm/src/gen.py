#!/usr/bin/env python3
"""Generate params.h: an integer matrix whose only eigenvector (for its
integer eigenvalue) is the byte vector of the flag, plus the SHA-256 of the flag.

Construction: let v be the flag bytes (length n). Build W (n x (n-1)) with
columns w_k = v[k+1]*e_k - v[k]*e_{k+1}; every column is orthogonal to v and
the columns span v^perp. Pick a random full-rank U (n x (n-1)) and set

    M = lambda*I + U*W^T

Then M*v = lambda*v, and ker(M - lambda*I) = span(v) because U has full
column rank and the columns of W span exactly v^perp.
"""
import hashlib
import random
import sys
from pathlib import Path

import numpy as np

FLAG = b"ctfcup{99aeaf6c1fb1d156e4194be638825e6f}"
LAMBDA = 1337
SEED = 0xBABE
PRIME = (1 << 61) - 1  # for modular rank checks


def rank_mod_p(rows: list[list[int]], p: int = PRIME) -> int:
    """Rank over GF(p). Over Q the rank is >= this, so hitting the maximum
    possible rank mod p proves full rank over Q."""
    a = [[x % p for x in row] for row in rows]
    rank = 0
    ncols = len(a[0])
    for col in range(ncols):
        pivot = next((r for r in range(rank, len(a)) if a[r][col]), None)
        if pivot is None:
            continue
        a[rank], a[pivot] = a[pivot], a[rank]
        inv = pow(a[rank][col], -1, p)
        a[rank] = [(x * inv) % p for x in a[rank]]
        for r in range(len(a)):
            if r != rank and a[r][col]:
                f = a[r][col]
                a[r] = [(x - f * y) % p for x, y in zip(a[r], a[rank])]
        rank += 1
    return rank


def build_matrix(v: list[int], rng: random.Random) -> list[list[int]]:
    n = len(v)
    # W[j][k]: column k is v[k+1]*e_k - v[k]*e_{k+1}
    W = [[0] * (n - 1) for _ in range(n)]
    for k in range(n - 1):
        W[k][k] = v[k + 1]
        W[k + 1][k] = -v[k]
    while True:
        U = [[rng.randint(-4, 4) for _ in range(n - 1)] for _ in range(n)]
        if rank_mod_p(U) == n - 1:
            break
    M = [[0] * n for _ in range(n)]
    for i in range(n):
        for j in range(n):
            M[i][j] = (LAMBDA if i == j else 0) + sum(U[i][k] * W[j][k] for k in range(n - 1))
    return M


def verify(M: list[list[int]], v: list[int]) -> None:
    n = len(v)
    y = [sum(M[i][j] * v[j] for j in range(n)) for i in range(n)]
    assert y == [LAMBDA * x for x in v], "v is not an eigenvector"
    shifted = [[M[i][j] - (LAMBDA if i == j else 0) for j in range(n)] for i in range(n)]
    assert rank_mod_p(shifted) == n - 1, "eigenspace too big"
    # Solve the way a player would: numeric eigen-decomposition, pick the
    # eigenvector that scales to printable ASCII.
    vals, vecs = np.linalg.eig(np.array(M, dtype=float))
    recovered = None
    for idx in range(n):
        if abs(vals[idx].imag) > 1e-6:
            continue
        vec = vecs[:, idx].real
        vec = vec / vec[0] * ord("c")
        cand = np.rint(vec).astype(int)
        if np.allclose(vec, cand, atol=1e-6) and all(32 <= c < 127 for c in cand):
            recovered = bytes(int(c) for c in cand)
    assert recovered == FLAG, f"solver recovered {recovered!r}"


def main() -> None:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).with_name("params.h")
    rng = random.Random(SEED)
    v = list(FLAG)
    n = len(v)
    M = build_matrix(v, rng)
    verify(M, v)
    digest = hashlib.sha256(FLAG).digest()

    lines = [
        "// Generated by gen.py - do not edit",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        f"constexpr std::size_t N = {n};",
        "",
        "constexpr std::uint8_t FLAG_HASH[32] = {",
        "    " + ", ".join(f"0x{b:02X}" for b in digest[:16]) + ",",
        "    " + ", ".join(f"0x{b:02X}" for b in digest[16:]) + ",",
        "};",
        "",
        "constexpr std::int64_t MATRIX[N][N] = {",
    ]
    for row in M:
        lines.append("    {" + ", ".join(f"{x}" for x in row) + "},")
    lines.append("};")
    lines.append("")
    out.write_text("\n".join(lines))
    print(f"wrote {out}: n={n}, lambda={LAMBDA}, sha256={digest.hex()}")


if __name__ == "__main__":
    main()
