#!/usr/bin/env python3
"""
gen_coeffs.py — turn a model JSON written by `text_lemniscate build --model`
into the coefficient ROMs of the Versal evaluator, plus test vectors.

    g(z) = prod_j (z - a_j) / ( c * prod_k (z - b_k)^m_k )

Outputs
  hls/g_coeffs.h      fp32 ROMs: zeros a_j, denominator factors b_k repeated
                      m_k times (padded to a multiple of the lane count), and
                      1/c split as  G_C_MANT_INV * 2^-G_C_EXP
  hls/test_vectors.h  test points with g evaluated in double precision from
                      the SAME fp32-rounded coefficients and inputs, so the C
                      testbench measures only the hardware's arithmetic error

usage: python3 tools/gen_coeffs.py model/hello.json [--lanes 8] [--out hls]
"""
import argparse
import json
import math
import os

import numpy as np


def f32(v):
    return np.float32(v)


def lit(v):
    """float literal that round-trips exactly to the same fp32 value"""
    v = float(np.float32(v))
    if v == 0.0:
        return "0.0f"
    s = "%.9g" % v
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def rows(name, vals, per=6):
    out = []
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(lit(v) for v in vals[i:i + per]) + ",")
    return f"static const float {name}[{len(vals)}] = {{\n" + "\n".join(out) + "\n};\n"


def reference(x, y, a, b, log_c):
    """log2|g| and arg g in double, at fp32 inputs, with fp32 coefficients"""
    z = x.astype(np.float64) + 1j * y.astype(np.float64)
    la = np.zeros(len(z)); th = np.zeros(len(z))
    for chunk in np.array_split(np.arange(len(a)), max(1, len(a) // 256)):
        d = z[:, None] - a[None, chunk]
        la += np.log(np.abs(d)).sum(1); th += np.angle(d).sum(1)
    for chunk in np.array_split(np.arange(len(b)), max(1, len(b) // 256)) if len(b) else []:
        d = z[:, None] - b[None, chunk]
        la -= np.log(np.abs(d)).sum(1); th -= np.angle(d).sum(1)
    la -= log_c
    th = np.angle(np.exp(1j * th))
    return la / math.log(2), th


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("model")
    ap.add_argument("--lanes", type=int, default=8)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "hls"))
    ap.add_argument("--vectors", type=int, default=3000, help="number of test points")
    a = ap.parse_args()
    d = json.load(open(a.model))
    L = a.lanes

    zeros = np.array([complex(*p) for p in d["zeros"]])
    poles = [complex(*p) for p in d["poles"]]
    den = np.array([b for b, m in zip(poles, d["pole_orders"]) for _ in range(m)], dtype=complex)
    zr, zi = zeros.real.astype(np.float32), zeros.imag.astype(np.float32)
    dr, di = den.real.astype(np.float32), den.imag.astype(np.float32)
    pad = lambda v: np.r_[v, np.zeros((-len(v)) % L + (L if len(v) == 0 else 0), np.float32)]
    log_c = float(d["log_c"])
    l2 = log_c / math.log(2)
    c_exp = math.floor(l2)
    c_mant_inv = 2.0 ** (c_exp - l2)            # in (0.5, 1]
    reg = d["region"]

    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, "g_coeffs.h"), "w") as f:
        f.write(f"""// Generated by tools/gen_coeffs.py from {os.path.basename(a.model)} -- do not edit.
// g(z) = prod_j (z - a_j) / ( c * prod_k (z - b_k) ),  z = x + iy
//   a_j = G_ZR[j] + i G_ZI[j]          (j < G_N_ZEROS)
//   b_k = G_DR[k] + i G_DI[k]          (k < G_N_DEN; poles repeated by their order)
//   1/c = G_C_MANT_INV * 2^(-G_C_EXP)   (log c = {log_c!r})
// text: {d.get('text', '')!r}, region: {reg}
#pragma once
#define G_COEFF_LANES {L}
#define G_N_ZEROS {len(zeros)}
#define G_N_ZEROS_PAD {len(pad(zr))}
#define G_N_DEN {len(den)}
#define G_N_DEN_PAD {len(pad(dr))}
#define G_C_EXP {c_exp}
static const float G_C_MANT_INV = {lit(c_mant_inv)};
""")
        f.write(rows("G_ZR", pad(zr)))
        f.write(rows("G_ZI", pad(zi)))
        f.write(rows("G_DR", pad(dr)))
        f.write(rows("G_DI", pad(di)))

    # ---- test vectors -------------------------------------------------------
    rng = np.random.default_rng(1)
    outline = np.array([complex(*p) for p in d["outline"]])
    if "box" in reg:
        x0, y0, x1, y1 = reg["box"]
    else:
        cx, cy, r = reg["circle"]
        x0, y0, x1, y1 = cx - r, cy - r, cx + r, cy + r
    n = a.vectors
    gx, gy = np.meshgrid(np.linspace(x0, x1, 60), np.linspace(y0, y1, 20))
    grid = (gx + 1j * gy).ravel()
    rand = x0 + (x1 - x0) * rng.uniform(size=n // 3) + 1j * (y0 + (y1 - y0) * rng.uniform(size=n // 3))
    # points just inside / outside the smoothed outline (normal ~ rotate tangent)
    k = rng.choice(len(outline), n // 6)
    t = outline[(k + 1) % len(outline)] - outline[k - 1]
    nrm = -1j * t / np.abs(t)                     # outline is counter-clockwise: -i*t points out
    near = np.r_[outline[k] + 2e-3 * nrm, outline[k] - 2e-3 * nrm]
    special = np.array([zeros[0], poles[0] if poles else zeros[1]])
    pts = np.r_[special, grid, rand, near][:max(n, 2)]
    x = pts.real.astype(np.float32); y = pts.imag.astype(np.float32)
    a32 = zr.astype(np.float64) + 1j * zi.astype(np.float64)
    b32 = dr.astype(np.float64) + 1j * di.astype(np.float64)
    with np.errstate(divide="ignore"):
        l2abs, arg = reference(x, y, a32, b32, log_c)
    with open(os.path.join(a.out, "test_vectors.h"), "w") as f:
        f.write(f"// Generated by tools/gen_coeffs.py: g in double precision at fp32 inputs -- do not edit.\n#pragma once\n#define TV_N {len(x)}\n")
        f.write(rows("TV_X", x)); f.write(rows("TV_Y", y))
        f.write(f"static const double TV_LOG2ABS[{len(x)}] = {{\n")
        for i in range(0, len(x), 4):
            f.write("    " + ", ".join(("%.17g" % v) if np.isfinite(v) else ("1e300" if v > 0 else "-1e300") for v in l2abs[i:i + 4]) + ",\n")
        f.write("};\n")
        f.write(f"static const double TV_ARG[{len(x)}] = {{\n")
        for i in range(0, len(x), 4):
            f.write("    " + ", ".join("%.17g" % (v if np.isfinite(v) else 0.0) for v in arg[i:i + 4]) + ",\n")
        f.write("};\n")
    inside = (l2abs < 0).sum()
    print(f"g_coeffs.h: {len(zeros)} zeros, {len(den)} denominator factors ({len(poles)} poles), "
          f"lanes {L}, 1/c = {c_mant_inv:.9f} * 2^-{c_exp}")
    print(f"test_vectors.h: {len(x)} points ({inside} inside the text, 1 zero, 1 pole)")


if __name__ == "__main__":
    main()
